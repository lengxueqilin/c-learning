/*
 * ============================================================
 *  03_printf_practice.c —— 第 1 课 · 示例 3：用 printf 排版
 * ============================================================
 *  这一节的核心认识：printf 就是把字符串"原样"吐到屏幕上，
 *  唯一的例外是遇到 \ 开头的转义字符。
 *  所以 —— 你写多少空格，屏幕上就有多少空格；排版完全由你控制。
 * ============================================================
 */

#include <stdio.h>

int main(void)
{
    /* 边框宽 34 个字符：+ 号开头，32 个减号，+ 号结尾 */
    printf("+--------------------------------+\n");
    printf("|         MY C JOURNEY           |\n");
    printf("+--------------------------------+\n");
    printf("| Name    : Alex                 |\n");
    printf("| Lesson  : 01 - Hello, C        |\n");
    printf("| Editor  : VS Code              |\n");
    printf("| Compiler: Apple clang (C17)    |\n");
    printf("+--------------------------------+\n");
    printf("| Progress: [####------]  40%%    |\n");
    printf("+--------------------------------+\n");

    /* 中文占两个英文字符的宽度，混在框里会数不准，所以单独放一行 */
    printf("\n目标：打牢编程基础，把每一行代码都\"真正看懂\"。\n");

    return 0;
}
