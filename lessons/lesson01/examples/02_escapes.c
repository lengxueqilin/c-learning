/*
 * ============================================================
 *  02_escapes.c —— 第 1 课 · 示例 2：注释与转义字符
 * ============================================================
 *  转义字符 = 用反斜杠 \ 开头，表示"看不见的字符"
 *  记住这个规律：\ 后面的字母不是字母本身，而是一个特殊含义。
 * ============================================================
 */

#include <stdio.h>

int main(void)
{
    // 这是单行注释：两个斜杠，从 // 一直到这一行结束，编译器完全无视

    /*
     * 这是多行注释：从斜杠星号开始，
     * 到星号斜杠结束，中间可以写很多行。
     * 注意：多行注释不能嵌套，别在里面再写一对！
     */

    printf("1. 最普通的一行\n");

    printf("2. 反斜杠 n 让光标跳到下一行\n\n");      /* 写两个 \n 就是空一行 */

    printf("3. 反斜杠 t 是制表符：姓名\t年龄\t城市\n");

    printf("4. 想在屏幕上打出双引号，要写 \\\" ：\n");
    printf("   他说：\"你好，世界\"\n");

    printf("5. 想在屏幕上打出反斜杠，要写两个：C:\\Users\\student\\code\n");

    printf("6. 想在屏幕上打出百分号，要写两个：正确率 100%%\n");

    return 0;
}
