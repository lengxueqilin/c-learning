#include <stdio.h>      /* 把 stdio.h 这个"工具箱"搬进来：printf 就住在里面 */

int main(void)          /* main 是程序的入口，操作系统从这里开始执行 */
{                       /* 左花括号：函数体开始 */

    printf("你好，C 语言！\n");   /* 打印一句话；\n 的作用是"换行" */
    printf("Hello, C!\n");       /* 再来一句，这次是英文 */

    return 0;           /* 把 0 交还给操作系统，表示"正常结束" */

}                       /* 右花括号：函数体结束 */
