/*
 * ============================================================
 *  04_value_passing.c —— 第 6 课 · 示例 4：值传递（本课最重要的一节）
 * ============================================================
 *  C 语言的函数传参，永远是"值传递"（call by value）：
 *      函数拿到的是实参的【一份拷贝】，不是原件。
 *
 *  一句话记住：
 *      【函数里改形参，外面永远不会变。】
 *
 *  ⭐ 这一节还回收了两个老伏笔：
 *     第 2 课作业的思考题、第 3 课作业的选做题，
 *     都是"交换两个变量"。当时我说"必须用临时变量"。
 *     现在你会看到：为什么"写个 swap 函数"在 C 里【做不到】，
 *     以及第 9 课的指针要怎么救它。
 * ============================================================
 */

#include <stdio.h>

/* ── 尝试写一个交换函数 —— 这个函数【注定失败】──────────── */
void swapWrong(int a, int b)
{
    int temp = a;
    a = b;
    b = temp;
    printf("  函数内部：a = %d, b = %d   <- 看起来换成功了！\n", a, b);
}

/* ── 对比：真正有效的做法是"在原地交换"，不是函数 ────────── */
/* 或者：把"交换"变成"返回新值"，但一个函数只能返回一个值…… */

/* ── 通过返回值，可以"改一个值" ──────────────────────────── */
int doubled(int n)
{
    n = n * 2;                      /* 改的是副本 */
    return n;                       /* 把结果送出去 */
}

/* ── 演示：参数是数组时情况不同（第 7 课细讲）────────────── */
/* 这里先不展开，只要记住："普通变量是拷贝，数组不是" */

int main(void)
{
    printf("=== 值传递的关键实验 ===\n\n");

    int x = 3, y = 8;
    printf("交换前：x = %d, y = %d\n", x, y);
    swapWrong(x, y);
    printf("交换后：x = %d, y = %d   <- 完全没变！\n", x, y);

    printf("\n为什么？因为函数拿到的是【拷贝】：\n");
    printf("  x 的原件(3) ──拷贝──> 形参 a\n");
    printf("  y 的原件(8) ──拷贝──> 形参 b\n");
    printf("  函数里换掉的是 a 和 b 这两个【副本】，原件根本没被碰过。\n");

    /* ── 正确姿势：用返回值把结果送出来 ───────────────────── */
    printf("\n=== 正确姿势：用返回值 ===\n");
    int v = 21;
    printf("调用前：v = %d\n", v);
    int result = doubled(v);
    printf("doubled(v) = %d, 但 v 依然是 %d\n", result, v);
    printf("想真的改变 v，必须【接收返回值】：v = doubled(v);\n");
    v = doubled(v);
    printf("执行 v = doubled(v) 之后：v = %d\n", v);

    /* ── ⭐ 那么"真的想改外面"怎么办？─────────────────────
     *
     * 第 9 课会学【指针】：把变量的"地址"传进去，
     * 函数就能照着地址去改原件：
     *
     *      void swap(int *a, int *b) {      ← 注意星号
     *          int temp = *a;               ← 星号表示"照着地址取内容"
     *          *a = *b;
     *          *b = temp;
     *      }
     *      swap(&x, &y);                    ← 传地址，不是传值
     *
     * 现在看不懂完全正常 —— 只要记住结论：
     *      函数【拿到的是副本】，所以改不了外面的普通变量。
     *      这就是为什么第 2、3 课的"交换"必须写在 main 里，
     *      而不能包成一个函数。
     *
     * 顺带回答一个常见疑问：
     *      "为什么一个函数不能返回两个值？"
     *      因为 C 的 return 只能带【一个】值。
     *      想送两个结果出来，就得用指针（第 9 课）或结构体（第 11 课）。
     */

    return 0;
}
