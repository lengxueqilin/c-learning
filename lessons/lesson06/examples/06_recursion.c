/*
 * ============================================================
 *  06_recursion.c —— 第 6 课 · 示例 6：递归入门
 * ============================================================
 *  递归 = 函数调用自己。
 *
 *  递归三要素（缺一个就会出问题）：
 *      ① 基准情形（base case）：什么时候停下来，直接给答案
 *      ② 向基准靠近：每次调用必须让问题【变小】
 *      ③ 调用自己：用"更小的问题"的答案，拼出"当前问题"的答案
 *
 *  ⭐ 本示例的第三部分会回收第 5 课的一个遗憾：
 *     "二进制输出需要倒序" —— 用递归天然就是正序。
 * ============================================================
 */

#include <stdio.h>

/* ── 递归 1：阶乘 n! = n × (n-1) × ... × 1 ──────────────── */
int factorial(int n)
{
    if (n <= 1) {
        return 1;                   /* ① 基准情形：0! 和 1! 都是 1 */
    }
    return n * factorial(n - 1);    /* ② 变小（n-1）  ③ 调用自己 */
}

/* ── 递归 2：斐波那契 1,1,2,3,5,8,13... ──────────────────
 *  ⚠️ 这个写法"能算但很慢"，原因见下面实测 */
int fib(int n)
{
    if (n <= 1) {
        return n;                   /* fib(0)=0, fib(1)=1 */
    }
    return fib(n - 1) + fib(n - 2); /* 一次调用分成两个 —— 指数级膨胀！ */
}

/* 给斐波那契加个"计数器"，数一数到底调用了多少次 */
int fibCalls = 0;
int fibCounted(int n)
{
    fibCalls++;
    if (n <= 1) {
        return n;
    }
    return fibCounted(n - 1) + fibCounted(n - 2);
}

/* ── 递归 3：二进制输出（天然正序！）───────────────────── */
void printBinary(int n)
{
    if (n > 1) {
        printBinary(n / 2);         /* 先把高位处理好（递归进去） */
    }
    printf("%d", n % 2);            /* 回来时才打印这一位 —— 于是顺序天然是对的 */
}

/* ── 对比说明：循环版为什么更麻烦 ──────────────────────
 * 循环里 % 2 取出来的是【从低位到高位】，想正序输出就得先存进数组再倒着读
 * —— 而数组第 7 课才学。递归用"调用栈"帮我们完成了这个倒序，所以 3 行就够了。
 */

int main(void)
{
    /* ── 阶乘 ─────────────────────────────────────────────── */
    printf("=== 递归 1：阶乘 ===\n");
    for (int i = 0; i <= 10; i++) {
        printf("%2d! = %d\n", i, factorial(i));
    }
    printf("（注意：13! 已经超过 int 上限 2147483647，会溢出 —— 第 3 课讲过）\n");

    /* ── 斐波那契：递归的"性能陷阱" ─────────────────────── */
    printf("\n=== 递归 2：斐波那契 ===\n");
    printf("前 12 项：");
    for (int i = 0; i <= 11; i++) {
        printf("%d ", fib(i));
    }
    printf("\n");

    fibCalls = 0;
    int r = fibCounted(20);
    printf("fib(20) = %d，为此函数被调用了 %d 次！\n", r, fibCalls);
    fibCalls = 0;
    r = fibCounted(30);
    printf("fib(30) = %d，为此函数被调用了 %d 次！（n 只大了 10，次数却涨了几十倍）\n",
           r, fibCalls);
    printf("原因：fib(30) 需要 fib(29) 和 fib(28)，而 fib(29) 又要 fib(28)…"
           "同一个值被重复算了无数遍。\n");
    printf("→ 递归很美，但【不是所有问题都该用递归】。这类问题用循环更快。\n");

    /* ── 二进制输出：递归的高光时刻 ─────────────────────── */
    printf("\n=== 递归 3：二进制输出（回收第 5 课的遗憾）===\n");

    int v = 13;
    printf("%d 的二进制 = ", v);
    printBinary(v);
    printf("\n");

    v = 255;
    printf("%d 的二进制 = ", v);
    printBinary(v);
    printf("\n");

    v = 1;
    printf("%d 的二进制 = ", v);
    printBinary(v);
    printf("\n");

    printf("\n为什么递归能天然正序？\n");
    printf("  printBinary(13) 先调 printBinary(6)，6 先调 3，3 先调 1；\n");
    printf("  1 打印 '1' → 3 打印 '1' → 6 打印 '0' → 13 打印 '1'  =  1101\n");
    printf("  递归调用像洋葱一样一层层包进去，最里层最先打印 —— 顺序天然正确。\n");

    return 0;
}
