/*
 * ============================================================
 *  03_scope.c —— 第 6 课 · 示例 3：局部变量与作用域
 * ============================================================
 *  局部变量（local variable）：在函数/代码块内部声明的变量，
 *                              只有"那一块"里能看见。
 *
 *  三条规则：
 *      1. 形参也是局部变量（它和函数里的其他局部变量一样）；
 *      2. 函数里的局部变量，出了函数就不存在了；
 *      3. 全局变量能被所有函数访问（但我们【尽量不用】，见文末）。
 * ============================================================
 */

#include <stdio.h>

/* ── 全局变量：所有函数都能读写（危险，慎用）──────────── */
int globalCounter = 0;
int sharedValue = 100;

/* 这个函数试图修改参数 —— 结果不会影响外面（第 4 节细讲） */
void tryToChange(int n)
{
    n = 999;                        /* 改的是"副本" */
    printf("  函数内部：n 被我改成了 %d\n", n);
}

/* 这个函数修改的是【真正的全局变量】—— 能改成功 */
void increaseGlobal(void)
{
    globalCounter++;
}

/* ── ⚠️ 关于"遮蔽（shadow）"────────────────────────────────
 * 如果函数参数名和全局变量同名，函数里看到的会是参数，不是全局变量。
 * 这种写法极其容易搞错，所以【不要这么做】：
 *
 *      int sharedValue = 100;              // 全局
 *      void f(int sharedValue) { ... }     // 形参把全局"遮蔽"了！
 *
 * 我们的编译标准里开了 -Wshadow，上面那种写法会直接报错：
 *      error: declaration shadows a variable in the global scope [-Wshadow]
 *
 * 这是好事 —— 编译器帮你拦住了这个坑。所以：全局变量换个名字，或者干脆别用全局变量。
 */

int main(void)
{
    /* ── 1. 局部变量只在自己的块里活着 ───────────────────── */
    int n = 5;
    printf("调用前：main 里的 n = %d\n", n);
    tryToChange(n);
    printf("调用后：main 里的 n = %d   <- 完全没变\n", n);

    /* ── 2. 形参也是局部变量 ─────────────────────────────── */
    printf("\n形参 a、b 只存在于 add 函数内部，main 里看不到它们。\n");

    /* ── 3. 块作用域：一对花括号就是一个作用域 ───────────── */
    {
        int inner = 100;
        printf("\n块内：inner = %d\n", inner);
    }
    /* printf("%d\n", inner);   // ❌ 错误：块外看不见 inner */

    /* ── 4. 关于"遮蔽（shadow）"：我们不允许这么写 ────────
     *
     * C 允许内层声明一个和外层同名的变量，内层会"遮蔽"外层：
     *
     *      int x = 1;
     *      {
     *          int x = 2;          // 这是另一个 x，遮蔽了外层的
     *          printf("%d", x);    // 打印 2
     *      }
     *      printf("%d", x);        // 打印 1（内层的 x 已经消失）
     *
     * 但我们的编译标准开了 -Wshadow，上面这种写法会【直接报错】：
     *      error: declaration shadows a local variable [-Wshadow]
     *
     * 这是好事 —— 同名变量是"改了哪个、用了哪个"搞混的头号原因。
     * 我们的纪律：【同一个作用域链上，不许出现同名变量】。
     * （想亲眼看报错？去 07_pitfall_playground.c 取消注释那段试试）
     */

    /* ── 5. 全局变量：任何函数都能改 ─────────────────────── */
    printf("\n全局变量演示：\n");
    printf("  globalCounter = %d\n", globalCounter);
    increaseGlobal();
    increaseGlobal();
    increaseGlobal();
    printf("  调了 3 次 increaseGlobal 之后 = %d\n", globalCounter);

    printf("  全局 sharedValue（没有任何函数改过它）= %d\n", sharedValue);

    /* ── ⚠️ 为什么我们尽量不用全局变量？────────────────────
     * 1. 任何函数都能改它 → 出了 bug 你根本不知道是谁改的；
     * 2. 函数之间"偷偷通信"，调用关系变得看不清楚；
     * 3. 项目一大（几千行、多个文件），全局变量就是 bug 温床。
     *
     * 正确做法：需要的数据从【参数】传进去，结果用【返回值】送出来。
     * 这就是"函数只做一件事、数据从参数进出"的原则。
     */

    return 0;
}
