/*
 * ============================================================
 *  01_first_function.c —— 第 6 课 · 示例 1：你的第一个函数
 * ============================================================
 *  从这一课起，你不再只是"写一串流程"，而是开始"造零件"。
 *
 *  函数的三个部分：
 *      返回类型  函数名(参数列表)
 *      {
 *          函数体
 *      }
 *
 *  读法：void printLine(void)
 *          "这个函数叫 printLine，
 *           它不接收任何参数（括号里的 void），
 *           也不返回任何值（开头的 void）"
 * ============================================================
 */

#include <stdio.h>

/* ── 函数 1：打印一条分隔线（无参数、无返回值）─────────── */
void printLine(void)
{
    printf("------------------------------\n");
}

/* ── 函数 2：打印 n 个星号（有参数、无返回值）───────────── */
void printStars(int n)
{
    for (int i = 0; i < n; i++) {
        printf("*");
    }
    printf("\n");
}

/* ── 函数 3：打印一个矩形（两个参数）───────────────────── */
void printRectangle(int rows, int cols)
{
    for (int r = 0; r < rows; r++) {
        printStars(cols);           /* ⭐ 函数可以调用另一个函数！ */
    }
}

int main(void)
{
    printLine();                    /* 调用：函数名 + 括号 + 分号 */
    printf("第 6 课：函数 —— 把代码打包起来\n");
    printLine();

    printf("\n10 个星号：");
    printStars(10);

    printf("\n一个 3 行 × 8 列的矩形：\n");
    printRectangle(3, 8);

    /* ── 为什么要用函数？看这三行调用就够了 ───────────────
     * 1. 主流程变得极短，一眼就能看懂"程序在干嘛"；
     * 2. 想改分隔线样式，只改 printLine 一处；
     * 3. printStars 被复用了两次（printRectangle 里又用了 3 次）。
     */

    return 0;
}
