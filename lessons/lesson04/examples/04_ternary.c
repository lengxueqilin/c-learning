/*
 * ============================================================
 *  04_ternary.c —— 第 4 课 · 示例 4：三目运算符 ? :
 * ============================================================
 *  语法：   条件 ? 条件为真时的值 : 条件为假时的值
 *
 *  它其实就是 if-else 的【表达式版】—— if-else 是"语句"，
 *  三目是"值"，所以可以塞进 printf、可以参与赋值。
 *
 *  什么时候用：简单的二选一（尤其是赋值/打印时）
 *  什么时候别用：分支里要做好几件事、或者嵌套超过一层
 * ============================================================
 */

#include <stdio.h>

int main(void)
{
    int score = 85;
    int a = 7, b = 2;

    /* ── 直接用"值" ───────────────────────────────────────── */
    printf("score = %d\n", score);
    printf("是否及格：%s\n", score >= 60 ? "是" : "否");
    printf("是否优秀：%s\n", score >= 90 ? "是" : "否");

    /* ── 赋值场景：三目最擅长的用法 ───────────────────────── */
    int max = a > b ? a : b;
    printf("\na = %d, b = %d\n", a, b);
    printf("较大的那个（max）= %d\n", max);

    int min = a < b ? a : b;
    printf("较小的那个（min）= %d\n", min);

    /* ── 和 if-else 写法对比 ─────────────────────────────── */
    /* if-else 版：4 行
        int max2 = 0;
        if (a > b) { max2 = a; } else { max2 = b; }

      三目版：1 行
        int max = a > b ? a : b;
       两者完全等价，三目在"简单二选一"时更清楚。 */

    /* ── 嵌套三目：能写，但已经不好读了 ───────────────────── */
    int n = -5;
    printf("\nn = %d\n", n);
    printf("符号判断（嵌套三目）：%s\n", n > 0 ? "正数" : (n < 0 ? "负数" : "零"));
    printf("（上式括号里的三目是必须的 —— 三目是【右结合】的）\n");

    /* ── 什么时候【不要】用三目 ───────────────────────────── */
    /* 如果分支里要做两件以上的事，就老老实实写 if-else：
        score >= 60 ? (printf("及格\n"), count++) : printf("不及格\n");   // ❌ 别这样写
       三目的可读性优势只在"二选一给一个值"的场景。 */

    /* ── 三目也可以当作小工具：0/1 转文字 ─────────────────── */
    int flag = 1;
    printf("\nflag = %d -> %s\n", flag, flag ? "真" : "假");
    printf("flag = 0 -> %s\n", (flag == 0) ? "真" : "假");

    return 0;
}
