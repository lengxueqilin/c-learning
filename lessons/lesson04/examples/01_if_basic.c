/*
 * ============================================================
 *  01_if_basic.c —— 第 4 课 · 示例 1：if 的基本形态
 * ============================================================
 *  从这一课起，程序终于会【看情况办事】了。
 *
 *  最关键的一句话：
 *      if 后面括号里放的，就是第 3 课算出来的那个 0 或 1。
 *      0  -> 跳过（假）
 *      非 0 -> 执行（真）
 * ============================================================
 */

#include <stdio.h>

int main(void)
{
    int score = 85;

    /* ── 形态 1：只有一条语句（能省花括号，但【不推荐】）────── */
    if (score >= 60)
        printf("及格了\n");

    /* ── 形态 2：加花括号（推荐！哪怕只有一条语句）────────── */
    if (score >= 60) {
        printf("score = %d\n", score);
        printf("及格了，可以进入下一课\n");
    }

    /* ── 形态 3：条件不成立时什么都不做 ───────────────────── */
    if (score >= 90) {
        printf("这一行不会执行\n");
    }
    printf("程序继续往下走（if 拦不住它）\n");

    /* ── 条件就是"0 或 1"：直接用第 3 课的表达式 ───────────── */
    int n = 17;
    if (n % 2) {                    /* 等价于 n % 2 != 0 */
        printf("%d 是奇数（这里用的是 n %% 2 本身当条件）\n", n);
    }
    if (n % 3 == 0) {
        printf("这一行不会执行，因为 17 不能被 3 整除\n");
    }

    /* ── ⭐ 实战：除法守卫（第 3 课那个陷阱的正式解法）──────── */
    int a = 7;
    int b = 0;

    printf("\n--- 除法守卫 ---\n");
    if (b != 0) {
        printf("a / b = %d\n", a / b);
    }
    if (b == 0) {
        printf("除数 b 是 0，已拦下这次除法\n");
    }
    /* 第 3 课我们实测过：不分青红皂白地做 7 / 0，在这台机器上会静默返回 0。
     * 现在你可以先判断，再决定要不要除 —— 这就是 if 的第一个真实价值。 */

    /* ── ⚠️ 花括号纪律：省略花括号的经典翻车 ──────────────── */
    /*
        if (score >= 60)
            printf("及格\n");
            printf("这句其实【不在】 if 里面！\n");   // 缩进骗了你，它永远会执行
    */
    /* 记住：只要你写 if，就顺手写一对花括号。省下来的两个字符，不值得用一个 bug 换。 */

    return 0;
}
