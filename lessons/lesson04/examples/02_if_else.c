/*
 * ============================================================
 *  02_if_else.c —— 第 4 课 · 示例 2：if-else 二选一
 * ============================================================
 *  if      ：条件成立时做什么
 *  else    ：条件【不】成立时做什么
 *  两者一定【恰好执行一个】，不可能都执行，也不可能都不执行。
 * ============================================================
 */

#include <stdio.h>

int main(void)
{
    int n = -7;

    /* ── 最朴素的二选一 ───────────────────────────────────── */
    if (n >= 0) {
        printf("%d 是非负数\n", n);
    } else {
        printf("%d 是负数\n", n);
    }

    /* ── 经典应用：求绝对值 ───────────────────────────────── */
    int absValue = 0;
    if (n >= 0) {
        absValue = n;
    } else {
        absValue = -n;
    }
    printf("|%d| = %d\n", n, absValue);

    /* ── 判断奇偶并说出结论 ───────────────────────────────── */
    int m = 42;
    if (m % 2 == 0) {
        printf("%d 是偶数\n", m);
    } else {
        printf("%d 是奇数\n", m);
    }

    /* ── 花括号纪律：一边有，两边都要有 ───────────────────── */
    /*
        if (n > 0) {
            printf("正数\n");
        } else
            printf("非正数\n");      // ❌ 一边有括号一边没有，极易改错
    */
    /* 统一都加，就没这个问题。 */

    /* ── 另一种常见写法：直接算出 0/1，再用 if 判断 ─────────── */
    int isEven = (m % 2 == 0);
    if (isEven) {
        printf("（isEven 里存的就是 %d）\n", isEven);
    }

    return 0;
}
