/*
 * ============================================================
 *  03_else_if_chain.c —— 第 4 课 · 示例 3：else if 链（多分支）
 * ============================================================
 *  三个必须记住的点：
 *    1. else if 链是【从上往下依次判断】，一旦命中就【整条链结束】；
 *    2. 所以【顺序至关重要】—— 范围判断要从苛刻到宽松（通常从高到低）；
 *    3. 最后一个 else 是可选的兜底（"以上都不是"）。
 * ============================================================
 */

#include <stdio.h>

int main(void)
{
    int score = 85;

    /* ── ✅ 正确顺序：从高到低 ───────────────────────────── */
    printf("score = %d\n\n", score);
    if (score >= 90) {
        printf("正确顺序的结果：等级 A\n");
    } else if (score >= 80) {
        printf("正确顺序的结果：等级 B\n");
    } else if (score >= 70) {
        printf("正确顺序的结果：等级 C\n");
    } else if (score >= 60) {
        printf("正确顺序的结果：等级 D\n");
    } else {
        printf("正确顺序的结果：等级 F\n");
    }

    /* ── ❌ 错误顺序：从低到高 —— 结果永远错 ───────────────── */
    printf("\n--- 把顺序倒过来（错误示范）---\n");
    if (score >= 60) {
        printf("错误顺序的结果：等级 D   <- 85 分也先掉进这里！\n");
    } else if (score >= 70) {
        printf("错误顺序的结果：等级 C   <- 永远轮不到\n");
    } else if (score >= 80) {
        printf("错误顺序的结果：等级 B   <- 永远轮不到\n");
    } else if (score >= 90) {
        printf("错误顺序的结果：等级 A   <- 永远轮不到\n");
    } else {
        printf("错误顺序的结果：等级 F\n");
    }
    /* 原因：else if 一旦命中就整条链结束。
     * 85 >= 60 已经成立，后面的分支连看都不看。 */

    /* ── 对比：写成多个【独立】的 if 会怎样 ───────────────── */
    printf("\n--- 写成几个独立的 if（不是 else if）---\n");
    if (score >= 60) {
        printf("如果分开写：及格\n");
    }
    if (score >= 80) {
        printf("如果分开写：良好\n");
    }
    if (score >= 90) {
        printf("如果分开写：优秀（不会打印）\n");
    }
    /* 独立的 if 会【每个都判断】，所以可能命中多个 —— 这是特性，也可能是 bug。
     * 要"只选一个"就用 else if 链；要"分别判断"就用独立 if。 */

    /* ── 真实案例：闰年（第 3 课的表达式，现在能说人话了）──── */
    printf("\n--- 闰年判断，这次输出文字 ---\n");
    int year = 1900;
    if ((year % 4 == 0 && year % 100 != 0) || year % 400 == 0) {
        printf("%d 是闰年\n", year);
    } else {
        printf("%d 不是闰年\n", year);
    }

    return 0;
}
