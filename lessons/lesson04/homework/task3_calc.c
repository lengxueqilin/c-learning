#include <stdio.h>

int main(void)
{
    int a = 0, b = 0;
    char op = 'A';
    printf("请输入表达式（格式：数字 运算符 数字，例如 7 * 2）：");
    scanf("%d %c %d", &a, &op, &b);

    switch (op)
    {
    case '+':
        printf("%d + %d = %d\n", a, b, a + b);
        break;
    case '-':
        printf("%d - %d = %d\n", a, b, a - b);
        break;
    case '*':
        printf("%d * %d = %d\n", a, b, a * b);
        break;
    case '/':
        if (b == 0)
        {
            printf("%d / %d: %s\n", a, b, "除数不能为 0");
        }
        else
        {
            printf("%d / %d = %d\n", a, b, a / b);
        }
        break;
    case '%':
        if (b == 0)
        {
            printf("%d %% %d: %s\n", a, b, "除数不能为 0");
        }
        else
        {
            printf("%d %% %d = %d\n", a, b, a % b);
        }
        break;
    default:
        printf("不支持的运算符：%c\n", op);
        break;
    }

    return 0;
}
