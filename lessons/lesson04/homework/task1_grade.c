#include <stdio.h>

int main(void)
{
    int score = 0;
    printf("请输入分数（0-100）：");
    scanf("%d", &score);

    // 默认等级
    char level = 'F';

    if (score >= 0 && score <= 100)
    {
        if (score >= 90)
        {
            level = 'A';
        }
        else if (score >= 80)
        {
            level = 'B';
        }
        else if (score >= 70)
        {
            level = 'C';
        }
        else if (score >= 60)
        {
            level = 'D';
        }
        printf("分数 %d -> 等级 %c\n", score, level);
    }
    else
    {
        printf("分数 %d -> 分数不合法（应在 0~100 之间）\n", score);
    }

    return 0;
}
