/* ===== 思考题（用文字回答，不用写代码）=========================
 *
 *  这一题里 case 后面有"故意不写语句"的情况（比如 case 1: case 3: ...），
 *  为什么这里的 fallthrough 是【正当的】，而不是 bug？
 *  （提示：想想"到底是谁在执行 days = 31;"这件事）
 *  我的想法：不写 break 是因为这几组 case 可以共享同一段输出代码，最后由该组
 *          最后的 case 12 执行输出后 break 终结掉
 *
 * ============================================================= */

#include <stdio.h>

int main(void)
{
    int year = 0, month = 0;
    printf("请输入年份和月份（空格隔开）：");
    scanf("%d %d", &year, &month);

    switch (month)
    {
    case 1:
    case 3:
    case 5:
    case 7:
    case 8:
    case 10:
    case 12:
        // case 穿透实现相同天数的月份共享输出语句
        printf("%d 年 %d 月有 31 天\n", year, month);
        break;
        // 都是 30 天
    case 4:
    case 6:
    case 9:
    case 11:
        // case 穿透实现相同天数的月份共享输出语句
        printf("%d 年 %d 月有 30 天\n", year, month);
        break;
    case 2:
        if ((year % 4 == 0 && year % 100 != 0) || (year % 400 == 0))
        {
            printf("%d 年 2 月有 29 天\n", year);
        }
        else
        {
            printf("%d 年 2 月有 28 天\n", year);
        }
        break;
    default:
        printf("月份 %d 不合法\n", month);
        break;
    }

    return 0;
}
