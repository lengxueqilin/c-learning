/*
 * ============================================================
 *  01_variables.c —— 第 2 课 · 示例 1：变量是什么
 * ============================================================
 *  一句话：变量就是"给一块内存起个名字"，之后用这个名字存取数据。
 *
 *  三个动作要分清（初学者最容易混）：
 *    声明（declaration）  int age;        告诉编译器"我要一个盒子，叫 age"
 *    赋值（assignment）   age = 18;       往盒子里放东西
 *    初始化（initialization）int age = 18;  声明的同时就放好东西（推荐！）
 * ============================================================
 */

#include <stdio.h>

int main(void)
{
    /* ── 第 1 种：先声明，后赋值 ─────────────────────────── */
    int age;            /* 声明：申请一个装整数的盒子，名字叫 age */
    age = 18;           /* 赋值：把 18 放进去（注意：= 是"放进去"，不是数学的"等于"） */

    /* ── 第 2 种：声明的同时初始化（更推荐，能防止"垃圾值"）── */
    int score = 95;

    /* ── 同一个类型可以一次声明多个 ─────────────────────── */
    int x = 1, y = 2, z = 3;

    printf("age   = %d\n", age);
    printf("score = %d\n", score);
    printf("x, y, z = %d, %d, %d\n", x, y, z);

    /* ── 变量之所以叫"变"量：里面的东西可以换 ────────────── */
    age = 19;
    printf("过完生日，age = %d\n", age);

    /* ── 用变量做计算：等号右边先算完，再放进左边 ────────── */
    score = score + 5;              /* 取出 95，加 5，再放回去 → 100 */
    printf("加 5 分之后，score = %d\n", score);

    /* ── 也可以两个变量互相参与运算 ──────────────────────── */
    int total = x + y + z;
    printf("x + y + z = %d\n", total);

    return 0;
}
