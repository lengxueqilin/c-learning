/*
 * ============================================================
 *  03_format_width.c —— 第 2 课 · 示例 3：宽度与精度（解决第 1 课的悬念）
 * ============================================================
 *  第 1 课你做信息卡时，是靠"手数空格"对齐的，我还提醒你 \t 很脆弱。
 *  现在给你真正的专业武器：在格式符里直接写"这一格占多少字符"。
 *
 *     %5d    → 占 5 格，右对齐（数字靠右）
 *     %-5d   → 占 5 格，左对齐（加一个减号）
 *     %05d   → 占 5 格，左补零
 *     %8.2f  → 占 8 格，保留 2 位小数
 *     %-10s  → 占 10 格，左对齐（s = 字符串，用来输出一段文字）
 * ============================================================
 */

#include <stdio.h>

int main(void)
{
    /* ── 1. 整数的宽度控制 ────────────────────────────────── */
    printf("--- 整数的宽度 ---\n");
    printf("[%5d]\n", 42);            /* 右对齐，前面补 3 个空格 */
    printf("[%-5d]\n", 42);           /* 左对齐，后面补 3 个空格 */
    printf("[%05d]\n", 42);           /* 左补零 */
    printf("[%5d]\n", 123456789);     /* 内容比格子还宽：格子自动撑大，不会截断 */

    /* ── 2. 小数的精度与宽度 ──────────────────────────────── */
    printf("\n--- 小数的精度 ---\n");
    double pi = 3.14159265358979;
    printf("pi = %f\n", pi);          /* 不写精度，默认保留 6 位小数 */
    printf("pi = %.2f\n", pi);        /* 只要 2 位小数（会四舍五入） */
    printf("pi = %.10f\n", pi);       /* 要 10 位，看看 double 能装多少 */
    printf("pi = [%10.2f]\n", pi);    /* 宽度 10 且保留 2 位：整体右对齐 */
    printf("pi = [%-10.2f]\n", pi);   /* 左对齐，方便看出格子的边界 */

    /* ── 3. 实战：一张"不用数空格"的整齐表格 ──────────────── */
    printf("\n--- 表格：全部靠宽度控制自动对齐 ---\n");
    printf("%-10s%8s%12s\n", "NAME", "SCORE", "HEIGHT(m)");
    printf("%-10s%8d%12.2f\n", "Alex",      95,  1.75);
    printf("%-10s%8d%12.2f\n", "Bob",      100,  1.82);
    printf("%-10s%8d%12.2f\n", "Catherine", 87,  1.68);

    /* 对比一下：如果名字比 10 格还长，会发生什么？ */
    printf("%-10s%8d%12.2f\n", "A-Very-Long-Name", 60, 1.70);
    printf("            ↑ 名字超过 10 格 → 这一行后面的列被整体推右，表格就歪了\n");
    printf("              结论：宽度要留足余量，宁可预留 15 格，也别刚好卡满\n");

    return 0;
}
