/*
 * ============================================================
 *  08_qa_rounding.c —— 第 2 课 · 答疑示例
 *  【疑问 2 的答案】为什么 %.2f 有时候不"四舍五入"？
 * ============================================================
 *  你在疑问里给了两个例子：
 *      printf("%.2f\n", 0.125);     →  0.12   （你以为是 0.13）
 *      printf("%.3f\n", 0.1245);    →  0.124  （你以为是 0.125）
 *
 *  这两个"意外"的原因其实是两个不同的机制，这个程序把它们都挖出来：
 *      机制 A：double 存不下精确的十进制小数（更常见）
 *      机制 B：正好卡在一半时，printf 会"向偶数舍入"（四舍六入五成双）
 * ============================================================
 */

#include <stdio.h>

int main(void)
{
    printf("=== 一、你的两个例子（原样复现）===\n");
    printf("printf(\"%%.2f\", 0.125)  →  %.2f\n", 0.125);
    printf("printf(\"%%.3f\", 0.1245) →  %.3f\n", 0.1245);

    printf("\n=== 二、把 double 的内部真相打印出来 ===\n");
    printf("(%%a 是十六进制浮点格式，能把存的二进制值原原本本显示出来)\n\n");
    printf("0.125  = %.20f   %%a = %a\n", 0.125, 0.125);
    printf("         ↑ 精确等于 1/8（因为 8 是 2 的幂），存得下！\n\n");
    printf("0.1245 = %.20f   %%a = %a\n", 0.1245, 0.1245);
    printf("         ↑ 实际存的是 0.12449999999999999956，比 0.1245 小！\n\n");
    printf("0.135  = %.20f   （比 0.135 大）\n", 0.135);
    printf("0.145  = %.20f   （比 0.145 小）\n", 0.145);

    printf("\n=== 三、机制 B：正好卡在一半时的\"向偶数舍入\" ===\n");
    printf("先看最好懂的整数例子（%%.0f）：\n");
    printf("  1.5 → %.0f      2.5 → %.0f      3.5 → %.0f\n", 1.5, 2.5, 3.5);
    printf("  看出来了吗：2.5 没有进位成 3，而是变成了 2（2 是偶数）\n\n");
    printf("再看小数（%%.2f，这些值都能被 double 精确存储）：\n");
    printf("  0.125 → %.2f    0.375 → %.2f    0.625 → %.2f    0.875 → %.2f\n",
           0.125, 0.375, 0.625, 0.875);
    printf("  规律：正好一半时，进位到\"末位是偶数\"的那一边\n");
    printf("        0.125 → 在 0.12 和 0.13 之间 → 选 0.12（2 是偶数）\n");
    printf("        0.375 → 在 0.37 和 0.38 之间 → 选 0.38（8 是偶数）\n");

    printf("\n=== 四、一句话对照 ===\n");
    printf("0.1245 → 存的比一半小（0.12449999...）→ 机制 A，直接舍去 → 0.124\n");
    printf("0.125  → 精确等于一半             → 机制 B，向偶数舍入 → 0.12\n");
    printf("0.135  → 存的比一半大（0.135000...888）  → 直接进位 → 0.14\n");
    printf("0.145  → 存的比一半小（0.144999...001）  → 直接舍去 → 0.14  ← 著名的坑！\n");

    printf("\n=== 五、工程结论（重要）===\n");
    printf("· double 只能精确表示\"分母是 2 的幂\"的分数，十进制小数大多存不准；\n");
    printf("· 所以 printf 的舍入结果，取决于\"它实际存了多少\"，而不是你写的那个数；\n");
    printf("· 涉及金额、成绩等需要十进制精确的场景，做法是：\n");
    printf("    用整数代替小数（金额以\"分\"为单位存成 int）——这是行业通行做法。\n");

    return 0;
}
