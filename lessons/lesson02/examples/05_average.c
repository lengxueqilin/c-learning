/*
 * ============================================================
 *  05_average.c —— 第 2 课 · 示例 5：综合练习（含一个大陷阱）
 * ============================================================
 *  任务：读入三门课的成绩，输出总分和平均分。
 *
 *  这里藏着一个 C 语言最经典的陷阱：
 *      整数 / 整数 = 整数（小数部分被直接丢掉！）
 *      7 / 2  的结果是 3，不是 3.5
 *  原因：两边都是整数，编译器就按整数规则算，小数部分直接"砍掉"（不是四舍五入）。
 *  解法：让其中一边变成小数 —— 写 3.0 或者除以 3.0。
 * ============================================================
 */

#include <stdio.h>

int main(void)
{
    int s1 = 0, s2 = 0, s3 = 0;

    printf("请输入三门课的成绩（用空格隔开，例如 90 81 85）：");
    scanf("%d %d %d", &s1, &s2, &s3);

    int sum = s1 + s2 + s3;

    printf("\n成绩单\n");
    printf("  第 1 门：%3d 分\n", s1);
    printf("  第 2 门：%3d 分\n", s2);
    printf("  第 3 门：%3d 分\n", s3);
    printf("  ------------------\n");
    printf("  总分  ：%3d 分\n", sum);

    /* ── ❌ 陷阱示范：整数除以整数 ─────────────────────────── */
    /* 注意 (double) 是"强制类型转换"，不加它编译器会警告格式不匹配（第 3 课细讲） */
    printf("  平均分（错误写法）：%.2f 分   ← sum / 3 先按整数算，小数已经被丢掉\n",
           (double)(sum / 3));

    /* ── ✅ 正确写法：除数是 3.0（小数）─────────────────────── */
    printf("  平均分（正确写法）：%.2f 分   ← sum / 3.0，运算按小数进行\n",
           sum / 3.0);

    /* ── 再验证一次这个陷阱本身 ───────────────────────────── */
    printf("\n陷阱验证：\n");
    printf("  7 / 2     = %d      ← 整数运算，小数被砍掉\n", 7 / 2);
    printf("  7 / 2.0   = %.2f    ← 有一个是小数，结果就是小数\n", 7 / 2.0);
    printf("  7.0 / 2   = %.2f    ← 反过来也一样\n", 7.0 / 2);

    /* ⚠️ 重要提醒：如果你输入的总分刚好能被 3 整除（比如 90 80 85 → 255），
     *    上面两种写法会打印出一样的结果。这不是"错误写法变对了"，
     *    只是这次运气好、小数正好是 0 而已 —— 看 7 / 2 那行就知道它的真面目。 */

    return 0;
}
