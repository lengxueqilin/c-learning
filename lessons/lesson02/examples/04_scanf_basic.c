/*
 * ============================================================
 *  04_scanf_basic.c —— 第 2 课 · 示例 4：让程序听懂键盘（scanf）
 * ============================================================
 *  直到现在，程序都只会"自己说"；从这一课起，它能"听你说"了。
 *
 *  两个必须记住的点：
 *    1. scanf 里，变量前面一定要加  &  （取地址符）
 *       printf("...", a)     ← 不需要 &
 *       scanf("...", &a)     ← 必须要 &
 *       记忆法：printf 是"把 a 的值拿出来给人看"；
 *               scanf  是"把数据放进 a 这个盒子里"——得先告诉它盒子在哪。
 *    2. 格式符要和变量类型对上：整数用 %d，double 用 %lf，char 用 %c
 *
 *  运行时：在底部终端里输入数字，按回车。
 * ============================================================
 */

#include <stdio.h>

int main(void)
{
    int a = 0;              /* 养成习惯：先给个初始值，万一下面输入失败也不会是垃圾值 */
    int b = 0;

    printf("请输入第一个整数（然后按回车）：");
    scanf("%d", &a);        /* 读一个整数，存到 a 里；&a 读作 "a 的地址" */

    printf("请输入第二个整数（然后按回车）：");
    scanf("%d", &b);

    printf("\n你输入的是 %d 和 %d\n", a, b);
    printf("%d + %d = %d\n", a, b, a + b);
    printf("%d - %d = %d\n", a, b, a - b);
    printf("%d * %d = %d\n", a, b, a * b);

    /* ── 一次读多个：两个数之间用空格或回车隔开都行 ────────── */
    /*
        int c = 0, d = 0;
        printf("请输入两个整数（空格隔开）：");
        scanf("%d %d", &c, &d);        // 一个 scanf 读两个变量，每个都要 &
        printf("c = %d, d = %d\n", c, d);
    */

    /* ── scanf 的返回值：成功读到了几个数据（这个很有用）────── */
    /*
        int n = 0;
        int ok = scanf("%d", &n);      // 读成功返回 1，读到文件结尾返回 0/-1
        if (ok == 1) { ... }           // 这是"检查输入是否合法"的起点，第 4 课讲 if
    */

    return 0;
}
