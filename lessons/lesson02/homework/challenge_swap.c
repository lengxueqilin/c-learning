/* ===== 思考题（用文字回答，不用写代码）=========================
 *
 *  不借助第三个变量，能不能完成交换？
 *  我的想法: a = a + b
 *           b = a - b
 *           a = a - b
 *  （提示：这要用到第 3 课才学的算术运算符，先随便猜，猜错没关系）
 * ============================================================= */

#include <stdio.h>

int main(void)
{
    int a = 0, b = 0, temp = 0;

    printf("请输入两个整数（空格隔开）：");
    scanf("%d %d", &a, &b);

    printf("交换前：a = %d, b = %d\n", a, b);

    // 开始交换
    temp = a;
    a = b;
    b = temp;

    printf("交换后：a = %d, b = %d\n", a, b);

    return 0;
}
