#include <stdio.h>

int main(void)
{
    int age = 18;
    double height = 1.75;

    printf("年龄：%d 岁\n", age);

    int score = 0;
    printf("分数：%d\n", score);

    printf("请输入你的年龄：");
    scanf("%d", &age);

    char level = 'A';

    double average = (90 + 81) / 2.0;
    printf("平均分：%.2f\n", average);

    printf("身高：%.2f，等级：%c\n", height, level);

    return 0;
}
