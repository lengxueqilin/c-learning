/*
 * ============================================================
 *  02_modulo.c —— 第 3 课 · 示例 2：取余 % 的四大用途
 * ============================================================
 *  % 是 C 语言里被新手严重低估的运算符。它有三个黄金用途：
 *      1. 判断整除 / 奇偶
 *      2. 把一个数的【每一位】拆出来
 *      3. 把大范围的值映射到小范围（分组、循环、取模）
 *  （第 4 个用途要等第 5 课学了循环才能完全发挥：循环取余 = 进制转换）
 *
 *  ⚠️ 铁律：% 只能用于整数。10.0 % 3 会直接编译报错。
 * ============================================================
 */

#include <stdio.h>

int main(void)
{
    /* ── 用途 1：判断奇偶、判断整除 ───────────────────────── */
    int n = 17;

    printf("=== 用途 1：判断奇偶 / 整除 ===\n");
    printf("n = %d\n", n);
    printf("n %% 2 = %d          <- 余 0 是偶数，余 1 是奇数\n", n % 2);
    printf("n 是偶数吗？ %d      <- 表达式 n %% 2 == 0 的结果（0 假 / 1 真）\n", n % 2 == 0);
    printf("n 能被 3 整除吗？ %d\n", n % 3 == 0);
    printf("记住：a 能被 b 整除  <=>  a %% b == 0\n");

    /* ── 用途 2：拆位（经典必会）──────────────────────────── */
    int num = 483;

    printf("\n=== 用途 2：把 %d 的每一位拆出来 ===\n", num);
    printf("个位 = num %% 10        = %d\n", num % 10);
    printf("十位 = num / 10 %% 10   = %d\n", num / 10 % 10);
    printf("百位 = num / 100 %% 10  = %d\n", num / 100 % 10);
    printf("各位数字之和 = %d\n", num / 100 % 10 + num / 10 % 10 + num % 10);

    /* 拆位的原理拆开看（这三行是本课最值钱的推导）：
     *   483 / 10   = 48      （整数除法，把个位砍掉）
     *   48  % 10   = 8       （取余 10，取出最后一位）
     *   两步配合，就能从右往左一位一位地取出来
     */
    printf("\n拆位原理：先 / 10 砍掉尾巴，再 %% 10 取出新的尾巴\n");
    printf("  483 / 10 = %d,  再 %% 10 = %d\n", num / 10, num / 10 % 10);

    /* ── 用途 3：把大范围映射到小范围 ─────────────────────── */
    int seconds = 47;

    printf("\n=== 用途 3：映射 / 分组 ===\n");
    printf("%d 秒属于第 %d 号区间（每 10 秒一档，从 0 号开始编号）\n", seconds, seconds / 10);
    printf("%d 秒在这 10 秒里的第 %d 秒（用 47 %% 10 取出来）\n", seconds, seconds % 10);

    /* ── 用途 4：进制转换的零件（第 5 课组装）─────────────── */
    printf("\n=== 用途 4：进制转换（第 5 课学循环后组装成完整程序）===\n");
    printf("%d 转成二进制，每次 %% 2 得到一位：\n", 13);
    int x = 13;
    printf("  13 %% 2 = %d   13 / 2 = %d\n", x % 2, x / 2);
    x = x / 2;
    printf("   %d %% 2 = %d     %d / 2 = %d\n", x, x % 2, x, x / 2);
    x = x / 2;
    printf("   %d %% 2 = %d     %d / 2 = %d\n", x, x % 2, x, x / 2);
    printf("  （把余数倒过来读：1101 —— 正是 13 的二进制）\n");

    return 0;
}
