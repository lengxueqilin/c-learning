int main(void)
{
    int a = 7, b = 2;

    printf("这一行是正常的：a = %d, b = %d\n", a, b);

    /* ── 陷阱 1：把 == 写成 = （最危险：能编译，结果全错）──── */
    // int x = 5;
    // printf("x 等于 5 吗？ %d\n", x = 5);      /* 你以为在比较，其实在赋值！ */
    // printf("x 现在是 %d\n", x);

    /* ── 陷阱 2：整数除法 ─────────────────────────────────── */
    printf("陷阱 2：7 / 2 = %d（不是 3.5）\n", 7 / 2);
    printf("        7 / 2.0 = %.2f（这样才对）\n", 7 / 2.0);

    /* ── 陷阱 3：%% 只能用于整数 ──────────────────────────── */
    // printf("%d\n", 10.0 % 3);     /* error: 浮点数不能取余 */

    /* ── 陷阱 4：把比较写成赋值 ──────────────────────────── */
    // printf("%d\n", 17 % 2 = 0);   /* error: 左边不是可赋值的对象 */

    /* ── 陷阱 5：有符号整数溢出（UB，什么都不报）─────────── */
    // int big = 2147483647;         /* int 的最大值 */
    // int bigger = big + 1;         /* 溢出！结果变成 -2147483648 */
    // printf("big + 1 = %d\n", bigger);

    /* ── 陷阱 6：除以零 / 取余零（运行时会崩）────────────── */
    // int zero = 0;
    // printf("%d\n", a / zero);     /* 运行时崩溃：SIGFPE */
    // printf("%d\n", a % zero);     /* 同样崩溃 */

    /* ── 附：表达式结果未使用（一个友好的警告）──────────── */
    // a == b;                       /* warning: expression result unused */

    return 0;
}
