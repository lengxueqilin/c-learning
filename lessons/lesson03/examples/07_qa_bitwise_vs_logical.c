/*
 * ============================================================
 *  07_qa_bitwise_vs_logical.c —— 第 3 课 · 答疑示例
 *  【疑问 1 的答案】C 语言的 & 和 | 与 && 和 || 有什么区别？
 *                   Java 里那套规则在 C 里成立吗？
 * ============================================================
 *  一句话回答：
 *      Java 里 & 和 | 是【重载】的（对整数按位、对 boolean 做不短路的逻辑）；
 *      C  里 & 和 | 【只有按位一种含义】，C 语言根本没有"不短路的逻辑运算符"。
 *
 *  这个程序用实验证明这件事（全部输出都是本机实测）。
 * ============================================================
 */

#include <stdio.h>

int main(void)
{
    /* ── 一、& 和 | 是按位运算，结果不是 0/1 ──────────────── */
    int x = 6, y = 3;

    printf("=== 一、& 和 | 是【按位】运算 ===\n");
    printf("先把两个数写成二进制：6 = 110, 3 = 011\n\n");
    printf("6 & 3  = %d    <- 按位与：110 & 011 = 010 = 2（结果不是 0/1！）\n", x & y);
    printf("6 | 3  = %d    <- 按位或：110 | 011 = 111 = 7\n", x | y);
    printf("6 && 3 = %d    <- 逻辑与：两边都非 0 -> 结果一定是 1\n", x && y);
    printf("6 || 3 = %d    <- 逻辑或：结果也一定是 1\n", x || y);
    printf("\n结论：& 和 | 会把两个数的【每一位】单独算，得到的是一个新的整数；\n");
    printf("      && 和 || 只关心\"是不是 0\"，结果永远是 1 或 0。\n");

    /* ── 二、决定性反例：2 & 1 和 2 && 1 结果相反 ─────────── */
    int a = 2, b = 1;

    printf("\n=== 二、决定性反例（这一段请重点看）===\n");
    printf("2 = 10, 1 = 01\n\n");
    printf("2 & 1  = %d    <- 按位与：10 & 01 = 00 = 0  —— 它说\"假\"\n", a & b);
    printf("2 && 1 = %d    <- 逻辑与：两边都非 0           —— 它说\"真\"\n", a && b);
    printf("\n同一个表达式，一个说假、一个说真 —— 它们根本不是一回事！\n");
    printf("（而 5 & 3 = 1、5 && 3 = 1 恰好相同，所以才容易骗过你）\n");

    /* ── 三、& 和 | 永远不短路：两边都会算 ────────────────── */
    printf("\n=== 三、& 和 | 不短路：两边永远都要求值 ===\n");

    int calls = 0;
    int r1 = (0 && (calls = 99));       /* && 短路：左边是 0，右边跳过 */
    printf("(0 && (calls = 99))  = %d,  calls = %d    <- && 短路，右边没执行\n", r1, calls);

    calls = 0;
    int r2 = (0 & (calls = 99));        /* & 不短路：右边照样执行 */
    printf("(0 &  (calls = 99))  = %d,  calls = %d   <- & 不短路，右边执行了！\n", r2, calls);

    printf("\n⚠️ 这一点很要命：\n");
    printf("   if (b != 0 && a / b > 2)    <- && 短路，b 是 0 时右边不执行，安全\n");
    printf("   if (b != 0 &  a / b > 2)    <- & 不短路，右边照样除 —— 除以零！\n");

    /* ── 四、~ 和 ! 也不是一回事 ─────────────────────────── */
    int zero = 0;

    printf("\n=== 四、~ 和 ! 同样不一样 ===\n");
    printf("!0 = %d     <- 逻辑非：把 0 变成\"真\"（结果是 1）\n", !zero);
    printf("~0 = %d    <- 按位取反：每一位翻转，0 变成全 1，即 -1\n", ~zero);

    /* ── 五、短路是语言保证，不是编译器心情 ───────────────── */
    printf("\n=== 五、短路是【语言保证】===\n");
    printf("C 标准（C17 6.5.13 / 6.5.14）明确规定：\n");
    printf("  && 和 || 的左侧求值之后，如果已经能确定结果，右侧【不进行求值】。\n");
    printf("所以上面第三组实验的结果，任何合规编译器都必须给你 —— 不是优化，是规定。\n\n");
    printf("顺便说：C 语言里【没有】\"一定要算完两边\"的逻辑运算符。\n");
    printf("如果你真的需要两边都执行，只能写成两句独立语句，或者用 & 配 0/1 值。\n");

    /* ── 六、Java vs C 对照表 ───────────────────────────── */
    printf("\n=== 六、Java 和 C 的这处区别 ===\n");
    printf("Java：& 和 | 是【重载】的\n");
    printf("        - 对整数  -> 按位运算\n");
    printf("        - 对 boolean -> 不短路的逻辑运算（两边都算）\n");
    printf("        - && 和 ||  -> 短路的逻辑运算\n\n");
    printf("C   ：& 和 | 【永远只是按位】，不存在 boolean 重载\n");
    printf("        - && 和 ||  -> 短路（这是 C 唯一的逻辑运算符）\n");
    printf("        - C99 虽然有 _Bool/bool，但 & 和 | 依然是按位，没有为它们新增逻辑含义\n");
    printf("\n所以：你那套 Java 经验搬到 C 里，第二行就会出错。\n");

    /* ── 七、一个真实的编译警告（务必知道）─────────────── */
    printf("\n=== 七、& 的优先级比 == 低（经典陷阱）===\n");
    printf("下面这行代码就会触发警告（完整报错见 lesson03-errors.md 第六节补充）：\n");
    printf("    int r = x & 1 == 0;    /* 注意 x 是变量 */\n");
    printf("clang 会警告：& has lower precedence than ==; == will be evaluated first\n");
    printf("它的真实含义是 x & (1 == 0)，也就是 x & 0，结果恒为 0 —— 完全不是你想的\"判断奇偶\"。\n");
    printf("正确写法：if ((x & 1) == 0)  或干脆用  if (x %% 2 == 0)\n");

    return 0;
}
