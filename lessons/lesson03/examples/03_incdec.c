/*
 * ============================================================
 *  03_incdec.c —— 第 3 课 · 示例 3：自增自减与复合赋值
 * ============================================================
 *  ++  自增 1        --  自减 1
 *  +=  -=  *=  /=  %=   复合赋值（"先算再放回去"的简写）
 *
 *  两条重要结论：
 *    1. 单独一行使用时，i++ 和 ++i 完全一样；
 *    2. 混在表达式里时，它们完全不同 —— 而且这是新手最容易写错的地方。
 * ============================================================
 */

#include <stdio.h>

int main(void)
{
    int i = 5;

    /* ── 单独使用时：四种写法效果完全一样 ─────────────────── */
    printf("=== 单独使用时：一模一样 ===\n");
    i = 5; i++;  printf("i = 5; i++;  结果 i = %d\n", i);
    i = 5; ++i;  printf("i = 5; ++i;  结果 i = %d\n", i);
    i = 5; i--;  printf("i = 5; i--;  结果 i = %d\n", i);
    i = 5; --i;  printf("i = 5; --i;  结果 i = %d\n", i);

    /* ── 混在表达式里：前缀和后缀完全不同 ─────────────────── */
    int a = 5, r = 0;

    printf("\n=== 混在表达式里：完全不同（危险区）===\n");

    a = 5;
    r = a++;            /* 后缀：先把 a 的旧值 5 交给 r，a 再变成 6 */
    printf("a = 5; r = a++;   ->  r = %d, a = %d\n", r, a);

    a = 5;
    r = ++a;            /* 前缀：a 先变成 6，再把 6 交给 r */
    printf("a = 5; r = ++a;   ->  r = %d, a = %d\n", r, a);

    printf("\n记忆法：++ 写在前面 = 先加再用；写在后面 = 先用再加。\n");

    /* ⚠️ 反面教材（我们绝不这么写）：
     *     printf("%d %d\n", i++, i);       参数求值顺序在 C 里是未指定的！
     *     a = a++ + ++a;                   同一变量被多次修改，属于未定义行为！
     * 一条纪律：自增自减【单独一行】使用，绝不塞进表达式里。
     */

    /* ── 复合赋值：x += 1 就是 x = x + 1 的简写 ────────────── */
    int x = 10;

    printf("\n=== 复合赋值 ===\n");
    printf("初始 x = %d\n", x);
    x += 5;  printf("x += 5  ->  %d\n", x);
    x -= 3;  printf("x -= 3  ->  %d\n", x);
    x *= 2;  printf("x *= 2  ->  %d\n", x);
    x /= 4;  printf("x /= 4  ->  %d   <- 注意还是整数除法\n", x);
    x %= 4;  printf("x %%= 4  ->  %d   <- 取余赋值\n", x);

    /* ── 累加器的写法（以后写循环求和全靠它）───────────────── */
    int sum = 0;
    sum += 1;       /* 等价于 sum = sum + 1，也等价于 sum++ */
    sum += 2;
    sum += 3;
    printf("\n累加器：sum 依次加 1、2、3 -> %d   （第 5 课循环就靠它求和）\n", sum);

    return 0;
}
