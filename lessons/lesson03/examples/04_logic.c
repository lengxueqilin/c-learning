/*
 * ============================================================
 *  04_logic.c —— 第 3 课 · 示例 4：关系运算符与逻辑运算符
 * ============================================================
 *  关系：>  <  >=  <=  ==  !=        结果是 0（假）或 1（真）
 *  逻辑：&& （与）  || （或）  ! （非）
 *
 *  这一节是【第 4 课 if 的地基】：
 *      if 的括号里，放的就是这里算出来的 0 或 1。
 * ============================================================
 */

#include <stdio.h>

int main(void)
{
    int a = 5, b = 3;

    /* ── 关系运算符 ───────────────────────────────────────── */
    printf("=== 关系运算符：结果只有 0 或 1 ===\n");
    printf("a = %d, b = %d\n", a, b);
    printf("a >  b  ->  %d\n", a > b);
    printf("a <  b  ->  %d\n", a < b);
    printf("a >= b  ->  %d\n", a >= b);
    printf("a <= b  ->  %d\n", a <= b);
    printf("a == b  ->  %d     <- 判断相等要写两个等号！\n", a == b);
    printf("a != b  ->  %d     <- != 读作\"不等于\"\n", a != b);

    /* ── C 语言里的"真"到底是什么 ─────────────────────────── */
    printf("\n=== C 语言里\"真\"是什么 ===\n");
    printf("0 是假，非 0 都是真（负数也算真！）\n");
    printf("!0 = %d      !5 = %d      !(-3) = %d\n", !0, !5, !(-3));

    /* 注意：这里特意用【变量】而不是写 5 && 3。
     * 因为直接写两个常量，clang 会警告 -Wconstant-logical-operand，
     * 怀疑你是不是把按位与 & 错写成了逻辑与 &&（这个警告很有用，见报错速查） */
    int t = 5, f = 0, neg = -3;
    printf("t && t = %d    t && f = %d    f || f = %d    f || neg = %d\n",
           t && t, t && f, f || f, f || neg);

    /* ── 短路求值：本课最重要的机制之一 ───────────────────── */
    printf("\n=== 短路求值（重要！）===\n");
    printf("规则：左边已经能决定结果时，右边【根本不执行】\n\n");

    int calls = 0;                  /* 用这个变量当"右边有没有被执行"的探针 */

    calls = 0;
    int r1 = (0 && (calls = 99));   /* 左边是 0 -> && 必为假 -> 右边跳过 */
    printf("(0 && (calls = 99))  = %d,  calls = %d   <- 右边没执行\n", r1, calls);

    calls = 0;
    int r2 = (1 || (calls = 99));   /* 左边是 1 -> || 必为真 -> 右边跳过 */
    printf("(1 || (calls = 99))  = %d,  calls = %d   <- 右边没执行\n", r2, calls);

    calls = 0;
    int r3 = (1 && (calls = 99));   /* 左边是 1 -> 还得看右边 -> 右边执行 */
    printf("(1 && (calls = 99))  = %d,  calls = %d  <- 这次执行了\n", r3, calls);

    printf("\n为什么要这样设计？为了安全和效率，例如：\n");
    printf("  if (b != 0 && a / b > 2)   <- b 是 0 时，右边不会算，避免除以零！\n");
    printf("  （这段要用到 if，第 4 课就能写了）\n");

    /* ── 实战：闰年判断，一个表达式搞定 ───────────────────── */
    printf("\n=== 实战：闰年判断 ===\n");
    printf("规则：能被 4 整除，但不能被 100 整除；或者能被 400 整除\n\n");
    printf("2000 是闰年吗？ %d\n", (2000 % 4 == 0 && 2000 % 100 != 0) || 2000 % 400 == 0);
    printf("1900 是闰年吗？ %d\n", (1900 % 4 == 0 && 1900 % 100 != 0) || 1900 % 400 == 0);
    printf("2024 是闰年吗？ %d\n", (2024 % 4 == 0 && 2024 % 100 != 0) || 2024 % 400 == 0);
    printf("2023 是闰年吗？ %d\n", (2023 % 4 == 0 && 2023 % 100 != 0) || 2023 % 400 == 0);
    printf("\n注意三层括号：&& 比 || 优先，所以先算两边的 && 再算 ||\n");

    return 0;
}
