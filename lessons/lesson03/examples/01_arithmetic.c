/*
 * ============================================================
 *  01_arithmetic.c —— 第 3 课 · 示例 1：五种算术运算
 * ============================================================
 *  +  加      -  减      *  乘（不是 ×）      /  除      %  取余
 *
 *  本课第一个关键认知：
 *      整数 / 整数 = 整数        （小数被直接砍掉）
 *      只要一边是小数 → 结果就是小数
 * ============================================================
 */

#include <stdio.h>

int main(void)
{
    int a = 7, b = 2;

    printf("a = %d, b = %d\n\n", a, b);

    printf("a + b = %d\n", a + b);
    printf("a - b = %d\n", a - b);
    printf("a * b = %d\n", a * b);
    printf("a / b = %d      <- 整数除法，小数被砍掉（不是四舍五入）\n", a / b);
    printf("a %% b = %d      <- 取余：7 除以 2，商 3 余 1\n", a % b);

    /* ── 想要精确的除法结果，必须让运算里出现小数 ───────────── */
    printf("\na / b 的精确值 = %.4f   <- 把 a 转成 double 再除\n", (double)a / b);

    /* ── 负数怎么办？C99 起有明确规定 ─────────────────────── */
    int c = -7;
    printf("\n--- 负数除法与取余 ---\n");
    printf("c = %d, b = %d\n", c, b);
    printf("c / b  = %d     <- -3.5 向 0 取整  = -3\n", c / b);
    printf("c %% b  = %d     <- 余数符号跟随【被除数】(c 是负的)\n", c % b);
    printf("c / -b = %d\n", c / -b);
    printf("c %% -b = %d     <- 余数符号依然跟随被除数\n", c % -b);
    printf("7 %% -3 = %d      <- 被除数是正的，所以余数为正\n", 7 % -3);

    printf("\n规律一句话：商向 0 取整，余数的符号跟被除数走。\n");

    return 0;
}
