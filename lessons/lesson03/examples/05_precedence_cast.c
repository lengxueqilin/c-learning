/*
 * ============================================================
 *  05_precedence_cast.c —— 第 3 课 · 示例 5：优先级与类型转换
 * ============================================================
 *  优先级（从高到低，本课够用的版本）：
 *      1. 括号 ()
 *      2. 单目：! ++ -- (类型) 负号
 *      3. 算术：* / %  然后  + -
 *      4. 关系：> < >= <=  然后  == !=
 *      5. 逻辑：&&  然后  ||
 *      6. 赋值：= += -= ...
 *
 *  记不住怎么办？【拿不准就加括号】—— 括号不要钱，bug 很贵。
 * ============================================================
 */

#include <stdio.h>

int main(void)
{
    /* ── 算术优先级 ───────────────────────────────────────── */
    printf("=== 优先级：先乘除后加减 ===\n");
    printf("1 + 2 * 3     = %d\n", 1 + 2 * 3);
    printf("(1 + 2) * 3   = %d\n", (1 + 2) * 3);
    printf("10 - 4 - 3    = %d    <- 同级左结合：(10-4)-3\n", 10 - 4 - 3);
    printf("100 / 10 / 2  = %d    <- 同级左结合：(100/10)/2\n", 100 / 10 / 2);

    /* ── 关系、逻辑的优先级 ───────────────────────────────── */
    printf("\n=== 算术 > 关系 > 逻辑 ===\n");
    printf("1 + 2 > 2       = %d   <- 等价于 (1+2) > 2\n", 1 + 2 > 2);
    printf("1 > 2 == 0      = %d   <- 等价于 (1>2) == 0\n", 1 > 2 == 0);
    printf("2 > 1 && 3 > 2  = %d   <- 等价于 (2>1) && (3>2)\n", 2 > 1 && 3 > 2);
    printf("!0 + 1          = %d   <- 等价于 (!0) + 1\n", !0 + 1);

    /* ── 赋值优先级最低，而且是右结合 ─────────────────────── */
    printf("\n=== 赋值：优先级最低 + 右结合 ===\n");
    int a = 0, b = 0, c = 0;
    a = b = c = 5;
    printf("a = b = c = 5;  ->  a=%d b=%d c=%d   <- 从右往左赋值\n", a, b, c);

    /* ── 类型转换 ─────────────────────────────────────────── */
    printf("\n=== 类型转换 ===\n");
    printf("隐式转换：3 / 2.0          = %.2f   <- int 被自动提升为 double\n", 3 / 2.0);
    printf("强制转换：(double)3 / 2    = %.2f   <- 推荐写法\n", (double)3 / 2);
    printf("括号范围：(double)(3 / 2)  = %.2f   <- 先整除再转，白转了！\n", (double)(3 / 2));

    printf("\n小数转整数：直接砍掉小数部分（向 0 取整，不是四舍五入）\n");
    printf("(int)3.99  = %d\n", (int)3.99);
    printf("(int)-3.99 = %d    <- 负数也是向 0 取整\n", (int)-3.99);
    printf("(int)2.5   = %d    <- 不是 3！\n", (int)2.5);

    printf("\n=== 一句话口诀 ===\n");
    printf("单目 > 算术 > 关系 > 逻辑与 > 逻辑或 > 赋值\n");
    printf("拿不准就加括号 —— 让别人（和三个月后的你）一眼看懂。\n");

    return 0;
}
