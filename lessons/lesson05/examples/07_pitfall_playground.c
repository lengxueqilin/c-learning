/*
 * ============================================================
 *  07_pitfall_playground.c —— 第 5 课 · 陷阱演练场
 * ============================================================
 *  用法：下面每个陷阱都被注释掉了，所以现在能正常编译。
 *        想看真实后果，删掉某一行的 // ，保存，然后编译运行。
 *        ⚠️ 其中"死循环"那几条要小心：跑起来就停不下来，按 Control + C 中止。
 *
 *  本课 8 大陷阱（真实报错原文见 lesson05-errors.md）：
 *    1. 忘记更新控制变量 → 死循环
 *    2. while / for 后面多写一个分号 → 空循环体（clang 会警告）
 *    3. 差一错误（off-by-one）：<= 和 < 用错
 *    4. break 只跳出一层（以为跳了两层）
 *    5. continue 之前忘了更新 → 死循环
 *    6. 在循环体里改循环变量 → 逻辑混乱
 *    7. 浮点数当循环条件（精度误差会让次数不对）
 *    8. while 的条件里写赋值（和第 4 课的 if 一样会被警告）
 * ============================================================
 */

#include <stdio.h>

int main(void)
{
    int i = 0;
    int total = 0;

    printf("这一行是正常的\n");

    /* ── 陷阱 1：忘记 i++ → 死循环 ───────────────────────── */
    // while (i < 5) {
    //     printf("%d ", i);
    //     /* 忘了 i++; → 永远打印 0 */
    // }

    /* ── 陷阱 2：循环后面多写分号 → 空循环体 ─────────────── */
    // while (i < 3);            /* 这个分号就是循环体（空的） */
    // {
    //     printf("这句只执行一次，而且和 while 无关\n");
    //     i++;
    // }
    // for (int k = 0; k < 3; k++);    /* for 也一样 */
    // { printf("同样只执行一次\n"); }

    /* ── 陷阱 3：差一错误（off-by-one）───────────────────── */
    printf("\n陷阱 3 对比：\n");
    total = 0;
    for (i = 1; i < 5; i++)  { total += i; }        /* 1+2+3+4 = 10 */
    printf("  i < 5  时求和 = %2d   （累加了 4 个数）\n", total);
    total = 0;
    for (i = 1; i <= 5; i++) { total += i; }        /* 1+2+3+4+5 = 15 */
    printf("  i <= 5 时求和 = %2d   （累加了 5 个数）—— 差一个 5！\n", total);

    /* ── 陷阱 4：break 只跳一层 ──────────────────────────── */
    printf("\n陷阱 4：以为 break 能跳出两层\n");
    for (int a = 1; a <= 2; a++) {
        for (int b = 1; b <= 3; b++) {
            if (b == 2) { break; }      /* 只跳出 b 循环 */
            printf("  (%d,%d) ", a, b);
        }
        printf("外层 a=%d 这一轮还是走完了\n", a);
    }

    /* ── 陷阱 5：continue 之前忘了更新 → 死循环 ──────────── */
    // for (int k = 0; k < 10; ) {          /* 注意：更新被挪进了循环体 */
    //     if (k % 2 == 0) { continue; }    /* k 是偶数就 continue → k 永远不增加！ */
    //     k++;
    // }

    /* ── 陷阱 6：在循环体里改循环变量 ─────────────────────
        for (int k = 0; k < 10; k++) {
            k += 2;              // ❌ 循环变量被改了两次，次数完全失控
        }
        想在循环体里改，就改用 while 并把更新写清楚。
    */

    /* ── 陷阱 7：用浮点数当循环条件 ─────────────────────── */
    // double d = 0.0;
    // while (d != 1.0) {          /* 0.1 累加 10 次不会正好等于 1.0！可能死循环 */
    //     d += 0.1;
    // }

    /* ── 陷阱 8：while 条件里写赋值（和 if 一样会警告）───── */
    // while (i = 5) { printf("%d ", i); }    /* 条件恒为真 → 死循环 + 警告 */

    printf("\n陷阱 7 的真相（浮点累加 10 次 0.1）：");
    double d = 0.0;
    for (int k = 0; k < 10; k++) { d += 0.1; }
    printf("d = %.20f，它 == 1.0 吗？ %d\n", d, d == 1.0);

    return 0;
}
