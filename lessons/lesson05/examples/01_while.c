/*
 * ============================================================
 *  01_while.c —— 第 5 课 · 示例 1：while 循环
 * ============================================================
 *  从这一课起，程序会【重复做同一件事】了 —— 这是计算机最擅长的活。
 *
 *  while 的三要素（缺一个就会出问题）：
 *      ① 初始化：给"控制变量"一个起始值
 *      ② 条件  ：成立就执行循环体
 *      ③ 更新  ：改变控制变量，否则【死循环】
 *
 *  语法：
 *      初始化;
 *      while (条件) {
 *          循环体;
 *          更新;
 *      }
 * ============================================================
 */

#include <stdio.h>

int main(void)
{
    /* ── 最基本的计数循环：打印 1~5 ───────────────────────── */
    int i = 1;                      /* ① 初始化 */
    printf("1~5：");
    while (i <= 5) {                /* ② 条件 */
        printf("%d ", i);
        i++;                        /* ③ 更新：少了这行就是死循环！ */
    }
    printf("\n");

    /* ── 倒数（条件从大往小走）───────────────────────────── */
    int count = 5;
    printf("倒数：");
    while (count > 0) {
        printf("%d... ", count);
        count--;
    }
    printf("发射！\n");

    /* ── 累加器模式：1 + 2 + ... + 100 ────────────────────── */
    int sum = 0;                    /* 累加器：从 0 开始 */
    int n = 1;
    while (n <= 100) {
        sum += n;                   /* 每次都往 sum 里加一点 */
        n++;
    }
    printf("1 + 2 + ... + 100 = %d\n", sum);

    /* ── 条件不一定是"计数"：数位拆解（第 3 课的零件，终于装上了）── */
    int num = 98765;
    int original = num;             /* 先备份，因为下面会把 num 改掉 */
    int digits = 0;                 /* 计数器 */
    printf("拆解 %d 的每一位（从个位开始）：", original);
    while (num > 0) {
        printf("%d ", num % 10);    /* 取出最后一位 */
        num /= 10;                  /* 砍掉最后一位 */
        digits++;                   /* 数一位 */
    }
    printf("\n它共有 %d 位\n", digits);

    /* ── 一次都不执行的情况：条件一开始就不成立 ──────────── */
    int x = 10;
    printf("x = %d，下面的循环体一次都不会执行：", x);
    while (x < 5) {
        printf("不会打印");
        x++;
    }
    printf("（直接跳过）\n");

    /* ── ⚠️ 死循环长什么样（这里用注释演示，别真跑）────────
        int k = 1;
        while (k <= 5) {
            printf("%d ", k);
            // 忘记写 k++;   →  k 永远是 1，条件永远成立，程序永远不会停！
        }
        // 中止办法：终端里按 Control + C
    */

    return 0;
}
