/*
 * ============================================================
 *  03_do_while.c —— 第 5 课 · 示例 3：do-while 循环
 * ============================================================
 *  特点：【先执行一次，再判断条件】—— 循环体至少执行一次。
 *
 *  语法：
 *      do {
 *          循环体;
 *      } while (条件);        ← ⚠️ 结尾这个分号不能少！
 *
 *  什么时候用？—— 【先做一次，再看要不要继续】的场景：
 *      输入校验（先读一次，不合法就再读）
 *      菜单（先显示一次，再问要不要重来）
 * ============================================================
 */

#include <stdio.h>

int main(void)
{
    /* ── 对比 1：条件一开始为假时，while 和 do-while 的差别 ── */
    int x = 10;

    printf("x = %d，条件是 x < 5\n", x);

    printf("while 版    ：");
    while (x < 5) {
        printf("这一行不会执行 ");
    }
    printf("（一次都没执行）\n");

    printf("do-while 版 ：");
    do {
        printf("至少执行了一次 ");
    } while (x < 5);
    printf("\n");

    /* ── 对比 2：条件一开始为真时，两者结果一样 ───────────── */
    int i = 1;
    printf("\nwhile 计数    ：");
    while (i <= 3) {
        printf("%d ", i);
        i++;
    }
    printf("\n");

    i = 1;
    printf("do-while 计数：");
    do {
        printf("%d ", i);
        i++;
    } while (i <= 3);
    printf("\n");

    /* ── ⭐ do-while 的真实用途：输入校验 ─────────────────
     * 思路：故意把变量初始化成"不合法"的值，这样【保证】至少进循环一次；
     *       读进来之后判断，不合法就再转一圈。
     */
    int score = -1;                 /* 故意给个非法初值 */
    int tries = 0;

    printf("\n--- 输入校验（请依次输入，非法值会被要求重输）---\n");
    do {
        tries++;
        printf("请输入 0~100 的分数：");
        scanf("%d", &score);

        if (score < 0 || score > 100) {
            printf("  %d 不合法，请重新输入\n", score);
        }
    } while (score < 0 || score > 100);

    printf("你输入的合法分数是 %d（共尝试 %d 次）\n", score, tries);

    /* ── 语法细节：while 后面那个分号 ─────────────────────── */
    int k = 0;
    do {
        k++;
    } while (k < 3);                /* ⚠️ 这里的 ; 不能少 */
    printf("\nk 最终 = %d\n", k);

    return 0;
}
