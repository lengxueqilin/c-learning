/*
 * ============================================================
 *  05_nested_loops.c —— 第 5 课 · 示例 5：嵌套循环（回收第 1 课伏笔）
 * ============================================================
 *  嵌套循环 = 循环里还有循环。
 *  外层走 1 步，内层要走完一整圈 —— 这是理解图案打印的关键。
 *
 *  ⭐ 第 1 课你曾手写 5 行 printf 画等腰三角形，当时我说：
 *     "第 5 课学了循环，3 行就能重写它"。现在就是收伏笔的时候。
 * ============================================================
 */

#include <stdio.h>

int main(void)
{
    /* ── 1. 九九乘法表 ────────────────────────────────────── */
    printf("=== 九九乘法表 ===\n");
    for (int i = 1; i <= 9; i++) {              /* 外层：行 */
        for (int j = 1; j <= i; j++) {          /* 内层：列（只到 i，所以是三角形） */
            printf("%d*%d=%-3d", j, i, i * j);  /* %-3d：占 3 格左对齐，保证列整齐 */
        }
        printf("\n");                           /* 一行结束，换行 */
    }

    /* ── 2. 等腰三角形（5 行）—— 第 1 课那道题的循环版 ────── */
    printf("\n=== 等腰三角形（5 行）===\n");
    for (int row = 1; row <= 5; row++) {
        for (int space = 0; space < 5 - row; space++) {
            printf(" ");                        /* 先补前导空格：逐行减少 */
        }
        for (int star = 0; star < 2 * row - 1; star++) {
            printf("*");                        /* 再打星号：逐行增加 2 个 */
        }
        printf("\n");                           /* 别忘了换行 */
    }
    printf("第 1 课你写了 5 行 printf，这里用循环同样画出它 —— 而且改成 9 行只要改一个数字。\n");

    /* ── 3. 菱形：把三角形"上下拼起来" ──────────────────── */
    printf("\n=== 菱形 ===\n");
    int size = 4;                               /* 上半部分（含最长那行）的行数 */
    for (int row = 1; row <= size; row++) {     /* 上半部分：1 → size */
        for (int space = 0; space < size - row; space++) printf(" ");
        for (int star = 0; star < 2 * row - 1; star++) printf("*");
        printf("\n");
    }
    for (int row = size - 1; row >= 1; row--) { /* 下半部分：size-1 → 1（倒着来） */
        for (int space = 0; space < size - row; space++) printf(" ");
        for (int star = 0; star < 2 * row - 1; star++) printf("*");
        printf("\n");
    }

    /* ── 4. 嵌套循环的执行次数：外层 × 内层 ──────────────── */
    printf("\n=== 嵌套循环走了多少步 ===\n");
    int steps = 0;
    for (int i = 1; i <= 4; i++) {
        for (int j = 1; j <= 3; j++) {
            steps++;
        }
    }
    printf("外层 4 次 × 内层 3 次 = 共执行 %d 次循环体\n", steps);
    printf("所以嵌套循环的代价是【乘法级】的 —— 后面做算法要特别小心这一点。\n");

    return 0;
}
