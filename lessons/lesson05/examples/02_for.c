/*
 * ============================================================
 *  02_for.c —— 第 5 课 · 示例 2：for 循环
 * ============================================================
 *  for 是"计数循环"的专用写法：把三要素压缩到一行，最不容易出错。
 *
 *  语法：
 *      for (初始化; 条件; 更新) {
 *          循环体;
 *      }
 *
 *  它和 while 完全等价：
 *      for (A; B; C) { D; }   ==   { A; while (B) { D; C; } }
 * ============================================================
 */

#include <stdio.h>

int main(void)
{
    /* ── 最基本的形态 ─────────────────────────────────────── */
    printf("1~5：");
    for (int i = 1; i <= 5; i++) {
        printf("%d ", i);
    }
    printf("\n");

    /* ── 常见变体 1：从 0 开始（第 7 课数组会大量使用这种写法）── */
    printf("从 0 开始：");
    for (int i = 0; i < 5; i++) {
        printf("%d ", i);
    }
    printf("\n");

    /* ── 常见变体 2：倒着数 ───────────────────────────────── */
    printf("倒着数：");
    for (int i = 5; i >= 1; i--) {
        printf("%d ", i);
    }
    printf("\n");

    /* ── 常见变体 3：步长不是 1 ───────────────────────────── */
    printf("步长 5  ：");
    for (int i = 0; i <= 20; i += 5) {
        printf("%d ", i);
    }
    printf("\n");

    printf("每次除以 2：");
    for (int i = 100; i >= 1; i /= 2) {
        printf("%d ", i);
    }
    printf("\n");

    /* ── 循环体只有一条语句时，花括号能省 —— 但我们【不省】── */
    /* 和 if 一样：花括号是你的安全气囊。 */

    /* ── 应用 1：累加 1~100 ───────────────────────────────── */
    int sum = 0;
    for (int i = 1; i <= 100; i++) {
        sum += i;
    }
    printf("1 + 2 + ... + 100 = %d\n", sum);

    /* ── 应用 2：计数（1~100 里有多少个能被 7 整除）──────── */
    int count = 0;
    for (int i = 1; i <= 100; i++) {
        if (i % 7 == 0) {
            count++;
        }
    }
    printf("1~100 中能被 7 整除的数有 %d 个\n", count);

    /* ── 应用 3：把一句话重复打印指定次数（"重复"的本职工作）── */
    printf("重复打印：");
    for (int i = 0; i < 20; i++) {
        printf("=");
    }
    printf("\n");

    /* ── 关于 i 的作用域（C99 起）─────────────────────────── */
    /* 在 for 的括号里声明的 i，出了这个循环就不存在了： */
    // printf("%d\n", i);        /* ❌ 错误：i 未声明 */

    /* 如果循环结束后还需要用这个变量，就在外面声明（老写法）： */
    int j = 0;
    for (j = 0; j < 3; j++) {
        /* 空循环体：什么都不做，只为把 j 加到 3 */
    }
    printf("循环结束后 j 仍然存在：j = %d\n", j);

    /* ── 空循环体要用花括号，别用分号（见陷阱演练场）─────── */
    int k = 0;
    for (int t = 0; t < 5; t++) {
        k += t;
    }
    printf("k = %d\n", k);

    return 0;
}
