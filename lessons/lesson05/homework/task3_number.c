#include <stdio.h>

int main(void)
{
    int n = 0;
    printf("请输入一个正整数（1~999999）：");
    scanf("%d", &n);

    int original = n;
    int digits = 0;
    int digitSum = 0;
    int reverse = 0;

    while (n > 0)
    {
        int digit = n % 10;
        digitSum += digit;
        reverse = reverse * 10 + digit;
        n /= 10;
        digits++;
    }

    printf("原数   = %d\n", original);
    printf("位数   = %d\n", digits);
    printf("各位和 = %d\n", digitSum);
    printf("反转数 = %d\n", reverse);

    return 0;
}
