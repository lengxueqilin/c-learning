#include <stdio.h>

int main(void)
{
    for (int t = 0; t < 3; t++)
    {
        printf("A ");
    }
    printf("\n");

    int sum = 0;
    for (int k = 1; k < 6; k++)
    {
        sum += k;
    }
    printf("1~5 的和 = %d\n", sum);

    int found = 0;
    for (int a = 1; a <= 3 && !found; a++)
    {
        for (int b = 1; b <= 3; b++)
        {
            if (a * b == 4)
            {
                printf("找到 a=%d b=%d\n", a, b);
                found = 1;
                break;
            }
        }
    }

    int sumOdd = 0;
    for (int k = 1; k <= 10; k++)
    {
        if (k % 2 == 0)
        {
            continue;
        }
        sumOdd += k;
    }
    printf("奇数和 = %d\n", sumOdd);

    int steps = 0;
    for (int k = 0; k < 10; k++)
    {
        steps++;
    }
    printf("steps = %d\n", steps);

    int n = 5, count = 0;
    for (int idx = 1; idx <= n; idx++)
    {
        count++;
    }
    printf("循环共执行了 %d 次\n", count);

    return 0;
}
