/* ===== 思考题（用文字回答，不用写代码）=========================
 *
 *  判断质数时，为什么"一发现因子就可以立刻 break"？
 *  为什么内层循环只需要试到 √n（代码里写成 d * d <= n），
 *  而不用一直试到 n - 1？
 *  （提示：如果 n = a × b 且 a ≤ b，那么 a 最大能是多少？）
 *
 *  我的想法：发现因子说明不是质数，没必要继续循环了，所以 break
 *          如果 n = a × b 且 a ≤ b，那么 a * a <= n，
 *          所以 a 最大只能是 √n，如果 a > √n 则 a * a > n 不符合逻辑
 *
 * ============================================================= */

#include <stdio.h>

int main(void)
{
    int count = 0;
    int isPrime = 1;

    for (int number = 2; number <= 100; number++)
    {
        isPrime = 1;

        for (int i = 2; i * i <= number; i++)
        {
            if (number % i == 0)
            {
                isPrime = 0;
                break;
            }
        }

        if (isPrime)
        {
            printf("%d ", number);
            count++;
            if (count % 10 == 0)
            {
                printf("\n");
            }
        }
    }

    if ((count % 10) != 0)
    {
        printf("\n");
    }

    printf("共 %d 个质数\n", count);

    return 0;
}
